def load_node():
    source=Path(__file__).with_name('dash_node.py')
    tree=ast.parse(source.read_text(),str(source))
    body=[node for node in tree.body if isinstance(node,(ast.FunctionDef,ast.ClassDef))]
    namespace=dict(globals(),Node=object,VehicleCommand=Command,PoseStamped=Pose,
        TwistStamped=Twist,ARM_SOURCE_COMPONENT=197)
    exec(compile(ast.Module(body=body,type_ignores=[]),str(source),'exec'),namespace)
    return namespace['DashNode']


DashNode=load_node()


class FlightApiTests(unittest.TestCase):
    def node(self):
        directory=tempfile.TemporaryDirectory();self.addCleanup(directory.cleanup)
        n=object.__new__(DashNode)
        n.core=DashCore();n.core.p.require_checked_route=True;n.core.owner='pilot';n.core.owner_hb=10;n.core.home=(0,0,0,0)
        n.lock=threading.Lock();n.a=SimpleNamespace(live=True,usb_telemetry=True)
        n.pos=Pos(10,0,0,0,0,True,0,0,0);n.fc=Fc(10,True,False,True,True)
        n.land=(10,True);n.fc_raw={}
        n.data=dict(status='live',age_s=.1,cell_m=.08,points=[[2.,0.]])
        n.depth_overlay=SimpleNamespace(snapshot=lambda now=None:n.data)
        n.course=CourseState(Path(directory.name)/'course.json')
        n.course.import_route([[0,0,1],[4,0,1]]);n.course.capture_anchor([0,0,0],0)
        n.course.update_preview(n.data,now=10)
        n.readiness=Mock(return_value=[]);n.freeze_interface=Mock()
        n.arm_pub=Mock();n.pub_pose=Mock();n.pub_twist=Mock();n.arm_request=None;n.n_out=0
        n.get_clock=lambda:SimpleNamespace(now=lambda:SimpleNamespace(nanoseconds=10_000_000_000,to_msg=lambda:None))
        n.get_logger=lambda:Mock()
        return n

    def test_arm_prepares_route_before_sending_one_normal_request(self):
        n=self.node()
        ok,msg=n.do_command(10,'pilot',{'op':'arm'})
        self.assertTrue(ok,msg);self.assertIsNotNone(n.core.queued_course)
        self.assertEqual(n.core.launch_state,'waiting_arm')
        n.arm_pub.publish.assert_called_once()
        sent=n.arm_pub.publish.call_args.args[0]
        self.assertEqual((sent.command,sent.param1,sent.param2),(400,1.,0.))
        n.pub_pose.publish.assert_not_called();n.pub_twist.publish.assert_not_called()
        # No ARM retry or mode request is generated by repeated control ticks.
        for i in range(3):
            with patch.object(time,'monotonic',return_value=10+i*.1):n._tick()
        n.arm_pub.publish.assert_called_once()

    def test_unowned_unready_stale_blocked_or_invalid_radius_never_arms(self):
        for case in ('owner','health','stale','blocked','radius','reference','armed'):
            n=self.node();body={'op':'arm'};client='pilot'
            if case=='owner':client='viewer'
            if case=='health':n.readiness.return_value=['VIO stale']
            if case=='stale':n.data['age_s']=2
            if case=='blocked':n.course.update_preview(dict(n.data,points=[[0,0]]),now=10)
            if case=='radius':body['radius_m']=1
            if case=='reference':n.core.home=(1,0,0,0)
            if case=='armed':n.fc.armed=True
            self.assertFalse(n.do_command(10,client,body)[0],case)
            n.arm_pub.publish.assert_not_called()
            self.assertIsNone(n.core.queued_course,case)

    def test_ground_start_queues_rc_launch_without_arming_and_stop_cancels(self):
        n=self.node()
        self.assertTrue(n.do_course(10,'pilot',{'op':'start','radius_m':6})[0])
        self.assertIsNotNone(n.core.queued_course);n.arm_pub.publish.assert_not_called()
        for op in ('preview','import','capture_anchor'):
            self.assertFalse(n.do_course(10,'pilot',{'op':op})[0])
        self.assertTrue(n.do_course(10,'pilot',{'op':'stop'})[0])
        self.assertIsNone(n.core.queued_course)
        n.arm_pub.publish.assert_not_called()

    @LEGACY_HOLDS
    def test_reference_loss_or_stale_depth_stops_timer_and_requests_hold(self):
        # Operator choice: stale depth alone never cancels a course (see course_safety).
        for case in ('reference','authority'):
            n=self.node();self.assertTrue(n.do_course(10,'pilot',{'op':'start','radius_m':6})[0])
            if case=='reference':n.course.invalidate_anchor('synthetic reset')
            else:n.core.was_offboard=True;n.fc.offboard_active=False
            with patch.object(time,'monotonic',return_value=10.1):n._tick()
            n.freeze_interface.assert_called_once()
            n.pub_pose.publish.assert_not_called();n.pub_twist.publish.assert_not_called()
            self.assertIsNone(n.core.queued_course)
            self.assertIn(n.core.mode,('failsafe','pilot'))

    def test_manual_arm_opt_out_does_not_start_course_and_kill_stays_available(self):
        n=self.node();n.readiness.side_effect=AssertionError('manual request is decided by PX4')
        self.assertTrue(n.do_command(10,'pilot',{'op':'arm','auto_course':False})[0])
        self.assertIsNone(n.core.queued_course)
        self.assertTrue(n.do_command(10,'viewer',{'op':'disarm'})[0])
        self.assertEqual(n.arm_pub.publish.call_args.args[0].param2,21196.)

    def test_airborne_depth_loss_keeps_the_course_without_freezing(self):
        n=self.node();self.assertTrue(n.do_course(10,'pilot',{'op':'start','radius_m':6})[0])
        n.fc.armed=True;n.fc.landed=False;n.pos.z=.5;n.data['age_s']=2
        with patch.object(time,'monotonic',return_value=10.1):n._tick()
        n.freeze_interface.assert_not_called()
        self.assertNotEqual(n.core.mode,'failsafe',n.core.reason)
        self.assertTrue(n.core.queued_course is not None or (n.core.course_run and n.core.course_run.active))
        n.data['age_s']=.1
        with patch.object(time,'monotonic',return_value=10.2):n._tick()
        self.assertNotEqual(n.core.mode,'failsafe',n.core.reason)


    def test_arm_outside_offboard_requests_offboard_then_arms_on_confirmation(self):
        n=self.node();n.fc.offboard_active=False
        ok,msg=n.do_command(10,'pilot',{'op':'arm'})          # ARM & fly course
        self.assertTrue(ok,msg)
        sent=[c.args[0] for c in n.arm_pub.publish.call_args_list]
        self.assertEqual([(s.command,s.param1,s.param2) for s in sent],[(176,1.,6.)])   # Offboard only, no ARM yet
        n.fc.offboard_active=True;n.fc.t=10.2
        with patch.object(time,'monotonic',return_value=10.2):n._tick()
        sent=[c.args[0] for c in n.arm_pub.publish.call_args_list]
        self.assertEqual((sent[-1].command,sent[-1].param1,sent[-1].param2),(400,1.,0.))

    def test_no_offboard_confirmation_never_arms(self):
        n=self.node();n.fc.offboard_active=False
        self.assertTrue(n.do_command(10,'pilot',{'op':'arm'})[0])
        n.fc.t=13.5
        with patch.object(time,'monotonic',return_value=13.5):n._tick()
        self.assertEqual([c.args[0].command for c in n.arm_pub.publish.call_args_list],[176])
        self.assertIn('did not enter Offboard',n.arm_request['message'])


